#!/usr/bin/env python
"""
common/base_topo.py

Shared topology skeleton for the WiFi security risk assessment lab.
DO NOT EDIT THIS FILE per-member — it defines the constant variables
(station count, roles, logging setup) that keep the three labs
(open / captive / wpa2) comparable. Only the AP security config
(ap_kwargs) should differ between member scripts.

Usage (from a member script):

    from common.base_topo import build_base_net

    net, ap1, stations, bot, attacker = build_base_net(
        ap_kwargs=dict(ssid='wpa2-test-network', mode='g',
                        channel='1', encrypt='wpa2', passwd='TestPass123!')
    )
"""

import os
import json
import time
import logging
from datetime import datetime

from mininet.log import setLogLevel, info
from mn_wifi.net import Mininet_wifi
from mn_wifi.cli import CLI

# ---- Constants shared across ALL three labs (do not change per-member) ----
N_CLIENT_STATIONS = 3     # "ordinary" clients in addition to bot + attacker
BOT_NAME = 'sta_bot'
ATTACKER_NAME = 'sta_attacker'
GATEWAY_IP = '10.0.0.1'
RESULTS_ROOT = os.path.join(os.path.dirname(__file__), '..', 'results')


def get_logger(network_type):
    """Returns a logger that writes to results/<network_type>/lab.log
    and stdout, with a consistent format across all three labs."""
    out_dir = os.path.join(RESULTS_ROOT, network_type)
    os.makedirs(out_dir, exist_ok=True)

    logger = logging.getLogger(network_type)
    logger.setLevel(logging.INFO)
    logger.handlers = []  # avoid duplicate handlers on re-run

    fmt = logging.Formatter('%(asctime)s [%(levelname)s] %(message)s')

    fh = logging.FileHandler(os.path.join(out_dir, 'lab.log'))
    fh.setFormatter(fmt)
    logger.addHandler(fh)

    sh = logging.StreamHandler()
    sh.setFormatter(fmt)
    logger.addHandler(sh)

    return logger, out_dir


def write_result(out_dir, test_name, result_dict):
    """Appends a single test result to results/<network_type>/results.jsonl
    using the standard schema agreed across the team."""
    result_dict.setdefault('timestamp', datetime.utcnow().isoformat() + 'Z')
    result_dict.setdefault('test', test_name)

    path = os.path.join(out_dir, 'results.jsonl')
    with open(path, 'a') as f:
        f.write(json.dumps(result_dict) + '\n')


def build_base_net(ap_kwargs, n_stations=N_CLIENT_STATIONS):
    """
    Builds the common topology: 1 AP (config supplied by caller),
    n ordinary client stations, 1 bot-traffic station, 1 attacker station.

    ap_kwargs: dict passed straight to net.addAccessPoint(), e.g.
        dict(ssid='open-test-network', mode='g', channel='1', encrypt=None)
        dict(ssid='wpa2-test-network', mode='g', channel='1',
             encrypt='wpa2', passwd='TestPass123!')

    Returns: (net, ap1, stations, bot, attacker)
    """
    net = Mininet_wifi()

    info('*** Adding access point\n')
    ap1 = net.addAccessPoint('ap1', **ap_kwargs)

    info('*** Adding client stations\n')
    stations = [
        net.addStation(f'sta{i}', ip=f'10.0.0.{i+1}/24')
        for i in range(1, n_stations + 1)
    ]

    info('*** Adding bot-traffic and attacker stations\n')
    bot = net.addStation(BOT_NAME, ip='10.0.0.50/24')
    attacker = net.addStation(ATTACKER_NAME, ip='10.0.0.99/24')

    info('*** Configuring nodes\n')
    net.configureWifiNodes()

    info('*** Building network\n')
    net.build()
    ap1.start([])

    return net, ap1, stations, bot, attacker


def run_cli(net):
    """Drop into the Mininet CLI for manual interaction/debugging."""
    CLI(net)


def teardown(net):
    info('*** Stopping network\n')
    net.stop()